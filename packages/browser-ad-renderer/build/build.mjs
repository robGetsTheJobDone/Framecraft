import {build} from 'esbuild';
import {readFile, writeFile, mkdir, copyFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
await mkdir('dist', {recursive: true});
const result = await build({entryPoints: ['src/harness.tsx'], bundle: true, write: false, format: 'iife', platform: 'browser', minify: true, define: {'process.env.NODE_ENV': '"production"'}});
const tailwind = await readFile(require.resolve('@tailwindcss/browser'), 'utf8');
await writeFile('src/harness-code.ts', `// Generated by build/build.mjs.\nexport const harnessCode: string = ${JSON.stringify(result.outputFiles[0].text)};\nexport const tailwindCode: string = ${JSON.stringify(tailwind)};\n`);
await copyFile(require.resolve('esbuild-wasm/esbuild.wasm'), 'dist/esbuild.wasm');

const versions={};
for(const name of ['react','remotion'])versions[name]=JSON.parse(await readFile(require.resolve(name+'/package.json'),'utf8')).version;
await writeFile('src/runtime-versions.ts', `// Generated by build/build.mjs.\nexport const packageRuntimeVersions = ${JSON.stringify(versions)} as const;\n`);
