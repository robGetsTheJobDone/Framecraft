import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {chromium} from '@playwright/test';
import {encodeWav} from '../packages/studio-audio/dist/index.js';

const packageRoot = fileURLToPath(new URL('../packages/studio-playground/', import.meta.url));
const require = createRequire(new URL('../packages/studio-playground/package.json', import.meta.url));
const vite = await import(pathToFileURL(require.resolve('vite')).href);
const production = process.env.PLAYGROUND_PRODUCTION === '1';
const server = production ? await vite.preview({root: packageRoot, logLevel: 'error', preview: {host: '127.0.0.1', port: 5174, strictPort: true}}) : await vite.createServer({root: packageRoot, logLevel: 'error', server: {host: '127.0.0.1', port: 5174, strictPort: true}});
if (!production) await server.listen();
let browser;
let page;
try {
  browser = await chromium.launch();
  page = await browser.newPage({viewport: {width: 1440, height: 1000}});
  const errors = [];
  page.on('pageerror', error => {errors.push(error.message); console.error(error.stack);});
  await page.route('**/api/config', route => route.fulfill({json: {configured: false}}));
  await page.goto('http://127.0.0.1:5174/?mode=timeline');
  await page.getByRole('heading', {name: 'Untitled film', exact: true}).waitFor({timeout: 60_000});
  await page.getByLabel('Message assistant').fill('title: Browser studio works');
  await page.getByRole('button', {name: 'Send ↑', exact: true}).click();
  await page.getByRole('heading', {name: 'Browser studio works', exact: true}).waitFor({timeout: 60_000});
  console.log('Playground: real agent demo edited timeline');
  const samples = Float32Array.from({length: 8000}, (_, index) => Math.sin(index * 2 * Math.PI * 220 / 8000) * 0.1);
  const wav = encodeWav({numberOfChannels: 1, length: samples.length, sampleRate: 8000, getChannelData: () => samples});
  await page.getByLabel('Upload media').setInputFiles({name: 'test-music.wav', mimeType: 'audio/wav', buffer: Buffer.from(await wav.arrayBuffer())});
  await page.locator('.clip.audio').first().waitFor();
  await page.locator('.clip.audio').first().click();
  await page.getByLabel('Volume', {exact: true}).fill('0.3');
  await page.getByRole('button', {name: 'Apply changes', exact: true}).click();
  await page.getByLabel('Volume', {exact: true}).waitFor();
  await page.getByRole('button', {name: 'Export audio', exact: true}).click();
  await page.getByRole('link', {name: 'Download deepbench.wav ↓'}).waitFor({timeout: 60_000});
  console.log('Playground: upload, inspector and audio export passed');
  const firstConversation = await page.getByLabel('Conversation', {exact: true}).inputValue();
  await page.getByRole('button', {name: 'New conversation', exact: true}).click();
  await page.getByRole('heading', {name: 'Untitled film', exact: true}).waitFor();
  assert.equal(await page.locator('.assets .asset').count(), 1);
  await page.getByText('Pierogi logo',{exact:true}).waitFor();
  await page.getByLabel('Conversation', {exact: true}).selectOption(firstConversation);
  await page.getByRole('heading', {name: 'Browser studio works', exact: true}).waitFor();
  await page.reload();
  await page.getByRole('heading', {name: 'Browser studio works', exact: true}).waitFor();
  assert.equal(await page.locator('.assets .asset').count(), 2);
  await page.getByRole('button', {name: 'Sample video', exact: true}).click();
  await page.locator('.clip.video').waitFor({timeout: 120_000});
  await page.getByRole('button', {name: '♫ Dub video', exact: true}).click();
  const dialog = page.getByRole('dialog', {name: 'Dubbing wizard'});
  await dialog.getByLabel('Source video', {exact: true}).selectOption({index: 1});
  await dialog.getByLabel('Voiceover brief').fill('A studio test script');
  await dialog.getByRole('button', {name: 'Draft script', exact: true}).click();
  await dialog.getByLabel('Segment 1 script', {exact: true}).fill('Reviewed test script');
  await dialog.getByRole('button', {name: 'Approve script', exact: true}).click();
  await dialog.getByRole('button', {name: 'Generate speech', exact: true}).click();
  await dialog.getByRole('button', {name: 'Add voiceover to timeline', exact: true}).click();
  await dialog.getByText('Voiceover saved to your project.', {exact: true}).waitFor();
  await page.getByRole('button', {name: 'Close dialog'}).click();
  console.log('Playground: conversation isolation, reload and dubbing panel passed');
  await page.getByRole('button', {name: 'Settings', exact: true}).click();
  await page.getByRole('dialog', {name: 'Connection settings'}).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.setViewportSize({width: 390, height: 844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.setViewportSize({width: 1440, height: 1000});
  await page.locator('.canvas').getByRole('button', {name: 'Play video', exact: true}).click();
  await page.waitForTimeout(700);
  await page.locator('.canvas').getByRole('button', {name: 'Pause video', exact: true}).click();
  await page.screenshot({path: '/tmp/deepbench-playground.png', fullPage: true});
  let gatewayCalls = 0;
  await page.route('https://gateway.test/v1/chat/completions', async route => {
    gatewayCalls++;
    assert.equal(route.request().postDataJSON().model, 'test-model');
    assert.equal(route.request().headers().authorization, 'Bearer test-session');
    await route.fulfill({contentType: 'application/json', headers: {'access-control-allow-origin': '*'}, body: JSON.stringify({id: 'chat-test', object: 'chat.completion', created: 1, model: 'test-model', choices: [{index: 0, message: {role: 'assistant', content: 'Gateway connection works.'}, finish_reason: 'stop'}], usage: {prompt_tokens: 1, completion_tokens: 1, total_tokens: 2}})});
  });
  await page.getByRole('button', {name: 'Settings', exact: true}).click();
  await page.getByLabel('Gateway base URL').fill('https://gateway.test/v1');
  await page.getByLabel('Model ID', {exact: true}).fill('test-model');
  await page.getByLabel('Gateway session token (optional)').fill('test-session');
  await page.getByRole('button', {name: 'Use gateway', exact: true}).click();
  assert.equal(gatewayCalls, 0, 'Connecting settings must not call a model automatically');
  await page.getByLabel('Message assistant').fill('Hello gateway');
  await page.getByRole('button', {name: 'Send ↑', exact: true}).click();
  await page.getByText('Gateway connection works.', {exact: true}).waitFor({timeout: 30_000});
  assert.ok(gatewayCalls > 0);
  assert.equal(await page.evaluate(() => JSON.stringify(localStorage).includes('test-session')), false);
  assert.deepEqual(errors, []);
  console.log('Playground smoke passed, including responsive layout. Screenshot: /tmp/deepbench-playground.png');
} catch (error) {
  console.error(await page?.locator('body').innerText());
  throw error;
} finally {
  await browser?.close();
  if (production) await new Promise(resolve => server.httpServer.close(resolve));
  else await server.close();
}
