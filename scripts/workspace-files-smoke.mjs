import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {chromium} from '@playwright/test';
const root = fileURLToPath(new URL('../packages/studio-playground/', import.meta.url));
const require = createRequire(new URL('../packages/studio-playground/package.json', import.meta.url));
const vite = await import(pathToFileURL(require.resolve('vite')).href);
const server = await vite.createServer({root, logLevel: 'error', server: {host: '127.0.0.1', port: 5176, strictPort: true, hmr: false}});
await server.listen();
const browser = await chromium.launch();
try {
  const context = await browser.newContext({viewport: {width: 1440, height: 1100}, permissions: ['clipboard-read', 'clipboard-write']});
  context.setDefaultTimeout(15000);
  await context.route('**/api/config', route => route.fulfill({json: {configured: false}}));
  let modelCalls = 0;
  await context.route('**/api/openai/**', route => {modelCalls++; return route.abort();});
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const command = async (tab, text) => {await tab.getByLabel('Message assistant').fill(text); await tab.getByRole('button', {name: 'Send ↑', exact: true}).click();};
  // Monaco's accessibility input contains only a viewport; inspect its model for full-file assertions.
  const runtimeURL = '/@fs' + fileURLToPath(new URL('../packages/studio/dist/monaco-runtime.js', import.meta.url));
  const editFile = async (tab, text) => {await tab.getByLabel('File contents').waitFor(); await tab.waitForFunction(async runtimeURL => {const {monaco} = await import(runtimeURL); const editor = monaco.editor.getEditors()[0]; return editor && !editor.getOption(monaco.editor.EditorOption.readOnly);}, runtimeURL); await tab.getByLabel('File contents').focus(); await tab.getByLabel('File contents').press('ControlOrMeta+a'); await tab.evaluate(text => navigator.clipboard.writeText(text), text); await tab.getByLabel('File contents').press('ControlOrMeta+v');};
  const readFile = async tab => {await tab.getByLabel('File contents').waitFor(); return tab.evaluate(async runtimeURL => {const {monaco} = await import(runtimeURL); return monaco.editor.getModels()[0]?.getValue();}, runtimeURL);};
  await page.goto('http://127.0.0.1:5176/?mode=timeline');
  await page.getByRole('heading', {name: 'Untitled film', exact: true}).waitFor();
  await page.getByRole('button', {name: 'Watch changes', exact: true}).click();
  assert.equal(await page.getByRole('switch', {name: 'Watch file changes'}).isChecked(), false);
  await page.getByRole('switch', {name: 'Watch file changes'}).check();
  await page.getByRole('button', {name: '← Back to studio', exact: true}).click();
  await command(page, '/files');
  assert.equal(await page.getByRole('heading', {name: 'Timeline', exact: true}).count(), 0);
  assert.equal(await page.getByLabel('Message assistant').count(), 0);
  await editFile(page, 'My first draft');
  await page.getByLabel('File contents').press('ControlOrMeta+s');
  await page.getByRole('button', {name: 'Discard edits and reload'}).waitFor({state: 'visible'});
  await page.getByRole('button', {name: '← Back to studio', exact: true}).click();
  await command(page, '/open /brief.md');
  assert.equal(await readFile(page), 'My first draft');
  await editFile(page, 'Unsaved local work');
  const other = await context.newPage();
  await other.goto('http://127.0.0.1:5176/?mode=timeline');
  await other.getByRole('heading', {name: 'Untitled film', exact: true}).waitFor();
  await command(other, '/files');
  await editFile(other, 'Changed in another tab');
  await other.getByRole('button', {name: 'Save file', exact: true}).click();
  await page.getByText('This file changed on disk.', {exact: false}).waitFor({timeout: 10000});
  assert.equal(await readFile(page), 'Unsaved local work');
  await page.getByRole('button', {name: 'Save file', exact: true}).click();
  await page.getByRole('alert').filter({hasText: 'ECONFLICT'}).waitFor();
  await page.getByRole('button', {name: 'Discard edits and reload'}).click();
  await page.waitForFunction(async runtimeURL => {const {monaco} = await import(runtimeURL); return monaco.editor.getModels()[0]?.getValue() === 'Changed in another tab';}, runtimeURL);
  await page.getByRole('button', {name: '← Back to studio', exact: true}).click();
  await command(page, '/changes');
  await page.getByRole('navigation', {name: 'File changes'}).getByRole('button').filter({hasText: '/brief.md'}).first().waitFor();
  await page.getByRole('switch', {name: 'Watch file changes'}).uncheck();
  await page.getByRole('button', {name: 'Clear change history'}).click();
  await editFile(other, 'Edited while watching is off');
  await other.getByRole('button', {name: 'Save file', exact: true}).click();
  await page.getByRole('button', {name: 'Refresh files', exact: true}).click();
  assert.equal(await page.getByRole('navigation', {name: 'File changes'}).getByRole('button').count(), 0);
  await page.getByRole('switch', {name: 'Watch file changes'}).check();
  assert.equal(await page.getByRole('navigation', {name: 'File changes'}).getByRole('button').count(), 0);
  await page.getByRole('button', {name: '← Back to studio', exact: true}).click();
  await command(page, '/open /project.json');
  const current = JSON.parse(await readFile(page));
  await editFile(page, '{broken');
  await page.getByRole('button', {name: 'Save file', exact: true}).click();
  await page.locator('.file-editor > p[role=alert]').waitFor();
  current.title = 'Live filesystem preview';
  await editFile(page, JSON.stringify(current, null, 2));
  await page.getByRole('button', {name: 'Save file', exact: true}).click();
  await page.getByRole('button', {name: '← Back to studio', exact: true}).click();
  await page.getByRole('heading', {name: 'Live filesystem preview', exact: true}).waitFor({timeout: 10000});
  await page.getByRole('button', {name: 'Files', exact: true}).click();
  await page.getByRole('button', {name: 'Folder /revisions', exact: true}).click();
  await page.getByRole('navigation', {name: 'File list'}).getByRole('button', {name: /^\/revisions\//}).first().click();
  const revision = await readFile(page);
  await page.getByLabel('File contents').focus(); await page.keyboard.insertText('must not change');
  assert.equal(await readFile(page), revision);
  await page.locator('.file-workspace').screenshot({path: '/tmp/deepbench-files.png'});
  await page.getByRole('button', {name: 'New conversation', exact: true}).click();
  await page.getByRole('heading', {name: 'Untitled film', exact: true}).waitFor();
  await command(page, '/files');
  assert.ok(!(await readFile(page)).includes('Changed in another tab'));
  assert.equal(modelCalls, 0); assert.deepEqual(errors, []);
  console.log('Files: local commands, edits, cross-tab conflict protection, change feed, project validation/live preview, read-only revisions and conversation isolation passed.');
} finally {await browser.close(); await server.close();}
